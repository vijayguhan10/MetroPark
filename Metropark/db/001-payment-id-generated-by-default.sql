-- Applied to the metropark database on 2026-08-07.
--
-- payments.payment_id was GENERATED ALWAYS AS IDENTITY, which makes PostgreSQL
-- reject any INSERT that supplies the column:
--
--   ERROR:  cannot insert a non-DEFAULT value into column "payment_id"
--   DETAIL: Column "payment_id" is an identity column defined as GENERATED ALWAYS.
--
-- The Redis-first design requires the id to exist before the row does:
-- PaymentRepository#allocatePaymentId reserves it from this column's sequence,
-- Redis stores the payment under it, the transaction reference embeds it
-- (TXN-<sessionId>-<paymentId>), and the consumer later inserts the row with
-- that same id. GENERATED ALWAYS makes that final insert impossible, so every
-- vehicle.entry event aborted its transaction and was dead lettered.
--
-- BY DEFAULT keeps the identity sequence and its default intact - inserts that
-- omit payment_id still auto-generate - while allowing an explicit value.
--
-- Reverse with: ALTER TABLE payments ALTER COLUMN payment_id SET GENERATED ALWAYS;

ALTER TABLE payments ALTER COLUMN payment_id SET GENERATED BY DEFAULT;
